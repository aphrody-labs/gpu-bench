#!/usr/bin/env bun
// Generates RESULTS.md from results/**/*.json. Every number in the tables comes from those files.
import { existsSync, readdirSync } from "node:fs";
import { join } from "node:path";
import { type Summary, percentile, path, summarize } from "./lib/common.ts";

interface RunA {
  labels: Record<string, string>;
  adapter: Record<string, string>;
  features: { timestampQuery: boolean };
  errors: string[];
  metrics: Record<string, number[]>;
  checks: Record<string, unknown>;
}
interface FileA { id: string; title: string; meta: { machine: Record<string, string>; pins: Record<string, string> }; failed?: string; runs: RunA[] }
interface RunB {
  labels: Record<string, string>;
  config: { n: number; canvas?: number[] };
  firstFrameMs?: number;
  helmetMs?: number;
  externalFirstFrameMs?: number;
  externalHelmetMs?: number;
  frameMs: number[];
  cpuMs: number[];
  gpuMs: number[];
  peakGpuMiB?: number;
  drawCalls?: number;
  triangles?: number;
}
interface FileB { id: string; title: string; meta: FileA["meta"]; failed?: string; perf: RunB[]; gpu: RunB[] }

const load = <T,>(dir: string): T[] => {
  const full = path("results", dir);
  return existsSync(full) ? readdirSync(full).filter((name) => name.endsWith(".json")).sort().map((name) => JSON.parse(require("node:fs").readFileSync(join(full, name), "utf8")) as T) : [];
};
const fmt = (value: number, digits = 3) => (Number.isFinite(value) ? (Math.abs(value) >= 100 ? value.toFixed(1) : Math.abs(value) >= 10 ? value.toFixed(2) : value.toFixed(digits)) : "n/a");
const cell = (s: Summary | undefined, digits = 3) => (s ? `${fmt(s.p50, digits)} / ${fmt(s.p95, digits)} / ${fmt(s.p99, digits)}<br>runs ${fmt(s.min, digits)}-${fmt(s.max, digits)}, cv ${s.cv.toFixed(1)}%` : "n/a");
const table = (header: string[], rows: string[][]) => [`| ${header.join(" | ")} |`, `| ${header.map(() => "---").join(" | ")} |`, ...rows.map((row) => `| ${row.join(" | ")} |`)].join("\n");

const filesA = load<FileA>("a");
const filesB = load<FileB>("b");
const sizes = existsSync(path("results", "sizes.json")) ? JSON.parse(require("node:fs").readFileSync(path("results", "sizes.json"), "utf8")) : {};
const summaryA = (file: FileA, metric: string) => (file.runs.length ? summarize(file.runs.map((run) => run.metrics[metric] ?? [])) : undefined);
const out: string[] = [];

const first = filesA[0] ?? filesB[0];
out.push("# Results", "", "Generated by `bun scripts/report.ts` from `results/**/*.json`; do not edit by hand.", "");
if (first) {
  const machine = first.meta.machine;
  out.push(`Machine: ${machine.gpu} | ${machine.cpu} | ${machine.os}`, `Tools: bun ${machine.bun}, ${machine.deno}, Chrome ${machine.chrome}`, `Run date: ${machine.date}`, "");
  out.push("Submodule pins:", "", table(["fork", "commit"], Object.entries(first.meta.pins).map(([name, sha]) => [name, `\`${sha}\``])), "");
}
out.push("Cell format: `p50 / p95 / p99` over all pooled samples, then the min-max and coefficient of variation (cv) of the per-run medians across runs. Timestamps are GPU pass time from timestamp queries; wall is encode+submit+wait-for-completion on the host.", "");

// ---- suite A ------------------------------------------------------------------------------------------------------
if (filesA.length) {
  const ok = filesA.filter((file) => file.runs.length > 0);
  out.push("## A. Dawn vs wgpu", "", "### Configurations", "");
  out.push(
    table(
      ["id", "engine", "host", "backend", "adapter", "runs", "timestamp-query", "errors", "runtime"],
      filesA.map((file) => {
        const run = file.runs[0];
        return [file.id, run?.labels.engine ?? "n/a", run?.labels.host ?? "n/a", run?.labels.backend ?? run?.labels.requestedBackend ?? "n/a", run ? `${run.adapter.description ?? ""} (${run.adapter.vendor ?? ""}/${run.adapter.device ?? ""})` : "n/a", String(file.runs.length), String(run?.features.timestampQuery ?? "n/a"), String(file.runs.reduce((count, r) => count + r.errors.length, 0)), run?.labels.runtime ?? "n/a"].map((v) => String(v).replace(/\|/g, "/"));
      }),
    ),
    "",
  );
  const failed = filesA.filter((file) => file.failed);
  if (failed.length) out.push("Could not run:", "", ...failed.map((file) => `- ${file.id}: ${file.failed!.split("\n")[0]}`), "");

  const group = (title: string, ids: string[]) => ok.filter((file) => ids.includes(file.id));
  const sections: Array<[string, string[]]> = [
    ["D3D12", ["bun-dawn-d3d12", "deno-wgpu-dx12", "native-dawn-d3d12", "native-wgpu-dx12", "chrome-dawn"]],
    ["Vulkan", ["bun-dawn-vulkan", "deno-wgpu-vulkan", "native-dawn-vulkan", "native-wgpu-vulkan"]],
    ["Firefox (wgpu, default backend)", ["firefox-wgpu", "chrome-dawn"]],
  ];
  const workloads = ["vecadd_64M", "reduce_64M", "matmul_2048", "cubes_100k_1080p", "fullscreen_1080p"];
  for (const [name, ids] of sections) {
    const files = group(name, ids);
    if (files.length < 1) continue;
    out.push(`### ${name}`, "");
    for (const [kind, suffix, digits] of [["GPU pass time (ms)", ".gpu_ms", 3], ["Wall time per submission (ms)", ".wall_ms", 3], ["CPU encode+submit (ms)", ".cpu_ms", 3]] as const) {
      out.push(`#### ${kind}`, "", table(["workload", ...files.map((f) => f.id)], workloads.map((workload) => [workload, ...files.map((file) => cell(summaryA(file, workload + suffix), digits))])), "");
    }
    out.push("#### API overhead", "", table(["metric", ...files.map((f) => f.id)], [
      ["buffer create+write+submit per second (higher is better)", ...files.map((file) => cell(summaryA(file, "buffer_create_write_submit_per_s"), 0))],
      ["shader module create + compilation info (ms)", ...files.map((file) => cell(summaryA(file, "shader_module_ms")))],
      ["render pipeline creation (ms)", ...files.map((file) => cell(summaryA(file, "render_pipeline_ms")))],
      ["compute pipeline creation (ms)", ...files.map((file) => cell(summaryA(file, "compute_pipeline_ms")))],
    ]), "");
    const throughput = (file: FileA, workload: string, work: number) => {
      const s = summaryA(file, `${workload}.gpu_ms`);
      return s ? `${fmt(work / (s.p50 / 1000))}` : "n/a";
    };
    out.push("#### Derived throughput at GPU p50", "", table(["metric", ...files.map((f) => f.id)], [
      ["vecadd GB/s (768 MiB moved)", ...files.map((file) => throughput(file, "vecadd_64M", (3 * 268_435_456) / 1e9))],
      ["reduce GB/s (256 MiB read)", ...files.map((file) => throughput(file, "reduce_64M", 268_435_456 / 1e9))],
      ["matmul GFLOP/s (2*2048^3)", ...files.map((file) => throughput(file, "matmul_2048", (2 * 2048 ** 3) / 1e9))],
      ["cubes 100k frames/s (GPU only)", ...files.map((file) => throughput(file, "cubes_100k_1080p", 1))],
      ["fullscreen frames/s (GPU only)", ...files.map((file) => throughput(file, "fullscreen_1080p", 1))],
    ]), "");
  }
  out.push("### Correctness checks (same on every run of a configuration)", "", table(["id", "vecadd", "reduce sum", "matmul", "cubes lit px", "fullscreen lit px"], ok.map((file) => {
    const checks = file.runs[0]!.checks;
    return [file.id, String(checks.vecadd_ok), String(checks.reduce_sum), String(checks.matmul_ok), String(checks.cubes_lit_pixels), String(checks.fullscreen_lit_pixels)];
  })), "");
}

// ---- suite B ------------------------------------------------------------------------------------------------------
if (filesB.length) {
  out.push("## B. three.js vs Bevy", "");
  const withRuns = filesB.filter((file) => file.perf.length > 0);
  const failedB = filesB.filter((file) => file.failed || file.perf.length === 0);
  if (failedB.length) out.push("Could not run:", "", ...failedB.map((file) => `- ${file.id}: ${(file.failed ?? "no runs").split("\n")[0]}`), "");
  const first = withRuns[0]?.perf[0];
  if (first) out.push(`Canvas ${first.config.canvas ? first.config.canvas.join("x") : "n/a"} physical pixels at devicePixelRatio ${first.labels.devicePixelRatio ?? "native"} (three.js); Bevy native window 1920x1080 logical at the native scale factor.`, "");
  for (const n of [1000, 10000, 100000]) {
    const files = withRuns.filter((file) => file.perf[0]?.config.n === n);
    if (!files.length) continue;
    const row = (label: string, value: (file: FileB) => string) => [label, ...files.map(value)];
    const frames = (file: FileB) => summarize(file.perf.map((run) => run.frameMs));
    const cpu = (file: FileB) => summarize(file.perf.map((run) => run.cpuMs));
    const gpu = (file: FileB) => (file.gpu.length ? summarize(file.gpu.map((run) => run.gpuMs)) : undefined);
    const scalar = (file: FileB, pick: (run: RunB) => number | undefined) => {
      const values = file.perf.map(pick).filter((v): v is number => v !== undefined && Number.isFinite(v));
      return values.length ? `${fmt(percentile(values, 50), 1)} (${fmt(Math.min(...values), 1)}-${fmt(Math.max(...values), 1)})` : "n/a";
    };
    out.push(`### ${n.toLocaleString("en")} cubes + DamagedHelmet`, "", table(["metric", ...files.map((f) => f.id)], [
      row("frame time ms p50 / p95 / p99 (uncapped)", (file) => cell(frames(file), 2)),
      row("fps at p50", (file) => fmt(1000 / frames(file).p50, 1)),
      row("main-thread CPU ms per frame", (file) => cell(cpu(file), 2)),
      row("GPU ms per frame (timestamps, separate runs)", (file) => (gpu(file) ? cell(gpu(file), 2) : "n/a")),
      row("startup to first frame ms, p50 (min-max)", (file) => scalar(file, (run) => run.firstFrameMs)),
      row("startup to helmet shown ms, p50 (min-max)", (file) => scalar(file, (run) => run.helmetMs)),
      row("native: spawn to first frame ms (external clock)", (file) => scalar(file, (run) => run.externalFirstFrameMs)),
      row("peak GPU memory above idle, MiB p50 (min-max)", (file) => scalar(file, (run) => run.peakGpuMiB)),
      row("backend / adapter", (file) => `${file.perf[0]!.labels.backend ?? "n/a"} / ${file.perf[0]!.labels.adapter ?? "n/a"}`),
      row("draw calls / triangles (three.js renderer.info)", (file) => (file.perf[0]!.drawCalls !== undefined ? `${file.perf[0]!.drawCalls} / ${file.perf[0]!.triangles}` : "n/a")),
      row("runs (perf / gpu)", (file) => `${file.perf.length} / ${file.gpu.length}`),
    ]), "");
  }
  if (Object.keys(sizes).length) {
    const bytes = (v?: { raw: number; brotli: number }) => (v ? `${v.raw.toLocaleString("en")} B raw, ${v.brotli.toLocaleString("en")} B brotli` : "n/a");
    out.push("### Shipped bytes", "", table(["artifact", "size"], [
      ["three.js scene bundle (bun build --minify, fork build/three.webgpu.js)", bytes(sizes.three_bundle_min)],
      ["Bevy wasm (wasm-bindgen + wasm-opt -O3)", bytes(sizes.bevy_wasm)],
      ["Bevy JS glue", bytes(sizes.bevy_js_glue)],
      ["Bevy native exe (release, fat LTO)", bytes(sizes.bevy_native_exe)],
      ["wgpu bench exe", bytes(sizes.wgpu_native_exe)],
      ["Dawn bench exe (static)", bytes(sizes.dawn_native_exe)],
      ["DamagedHelmet assets (identical for both)", sizes.helmet_assets_raw ? `${sizes.helmet_assets_raw.toLocaleString("en")} B raw` : "n/a"],
    ]), "");
  }
}
if (!filesA.length && !filesB.length) out.push("No results yet: run `bun scripts/run.ts bench a b`.", "");
await Bun.write(path("RESULTS.md"), `${out.join("\n")}\n`);
console.log(`RESULTS.md: ${out.length} lines, ${filesA.length} A configs, ${filesB.length} B configs`);
